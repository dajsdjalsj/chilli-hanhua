local function strip(s) return (s:gsub("^%s+", ""):gsub("%s+$", "")) end

local function names(s)
    local direct = lookup(s)
    if direct then return direct end
    -- Greedy whole-phrase composition. Unknown words cancel the composition.
    local words = {}
    for word in s:gmatch("%S+") do words[#words + 1] = word end
    local out, i = {}, 1
    while i <= #words do
        local found = false
        for n = math.min(7, #words - i + 1), 1, -1 do
            local zh = lookup(table.concat(words, " ", i, i + n - 1))
            if zh then
                out[#out + 1] = zh
                i = i + n
                found = true
                break
            end
        end
        if not found then return nil end
    end
    if #out > 0 then return table.concat(out) end
end

