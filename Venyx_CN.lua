            if inst[record.prop] == record.translated then inst[record.prop] = record.original end
        end)
    end
    if dirty then export(false) end
    if panel then panel:Destroy() end
    if ENV[STATE_KEY] and ENV[STATE_KEY].Stop == stop then ENV[STATE_KEY] = nil end
end
