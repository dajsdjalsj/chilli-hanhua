local function apply(inst, record)
    if not active or record.busy or not isTarget(inst) then return end
    local ok, original = pcall(function() return inst[record.prop] end)
    if not ok or type(original) ~= "string" or original == record.translated then return end
    local translated = Engine.Translate(original)
    collect(original, translated)
    record.original, record.translated = original, translated
    if translated ~= original then
        record.busy = true
        local wrote = pcall(function() inst[record.prop] = translated end)
        record.busy = false
        if wrote then translatedCount = translatedCount + 1 end
    end
end
local function handle(inst)
    if tracked[inst] or not isTarget(inst) then return end
    local prop
    if inst:IsA("TextBox") then prop = "PlaceholderText"
    elseif inst:IsA("TextLabel") or inst:IsA("TextButton") then prop = "Text"
    else return end
    local record = { prop = prop }
    tracked[inst] = record
    apply(inst, record)
    local ok, connection = pcall(function()
        return inst:GetPropertyChangedSignal(prop):Connect(function() apply(inst, record) end)
    end)
    if ok then connections[#connections + 1] = connection end
end
local function addTarget(root)
    if isTarget(root) then return end
    targets[#targets + 1] = root
    handle(root)
    for _, inst in ipairs(root:GetDescendants()) do handle(inst) end
    say("中文界面已启用；已处理 " .. translatedCount .. " 次文本更新")
end
local function inspect(inst, root)
    if isMarker(inst) then addTarget(findBranch(inst, root)) end
    handle(inst)
end
local function scan()
    for _, root in ipairs(getRoots()) do
        if not watched[root] then
            local ok, connection = pcall(function()
                return root.DescendantAdded:Connect(function(inst)
                    task.defer(function()
                        if not active then return end
                        pcall(function()
                            inspect(inst, root)
                            for _, child in ipairs(inst:GetDescendants()) do inspect(child, root) end
                        end)
                    end)
                end)
            end)
            if ok then watched[root] = true; connections[#connections + 1] = connection end
        end
        pcall(function()
            for _, inst in ipairs(root:GetDescendants()) do inspect(inst, root) end
        end)
    end
end
local function stop()
