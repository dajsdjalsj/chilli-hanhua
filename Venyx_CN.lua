translate = function(s, depth)
    depth = depth or 0
    if type(s) ~= "string" or depth > 12 or s == "" then return s end
    local direct = lookup(s)
    if direct then return direct end
    -- Preserve rich text tag names, color attributes and icon markup verbatim.
    if s:find("</?%a+[^>]*>") then
        local out, pos = {}, 1
        while pos <= #s do
            local a, b = s:find("</?%a+[^>]*>", pos)
            if not a then out[#out + 1] = plain(s:sub(pos), depth); break end
            out[#out + 1] = plain(s:sub(pos, a - 1), depth)
            out[#out + 1] = s:sub(a, b)
            pos = b + 1
        end
        return table.concat(out)
    end
    return plain(s, depth)
end

function Engine.Translate(s) return translate(s, 0) end
function Engine.IsIntentional(s)
    local core = strip(s)
    if keep[core] then return true end
    if core:match("^https?://") or core:match("^v%d[%d%.]*$") then return true end
    if core:match("^%$[%d%.,]+%a*$") or core:match("^[%d%.,]+[KMBTQakmbtq]+$") then return true end
    if core:match("^[xX][%d%.]+$") or core:match("^%a$") then return true end
    if core == "--" or core:match("^[%d%p%s]+$") then return true end
    return false
end
